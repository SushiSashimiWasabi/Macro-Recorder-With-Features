"""Key codes that work on both Windows and Mac.

Macro files store keys with Windows key codes ("vk"), whichever computer recorded them, so a
macro made on Windows plays on a Mac and the other way round. Windows and Mac number their keys
differently, so these tables translate between the two (for the usual US/ANSI key positions:
letters, numbers, punctuation, F-keys, the number pad, arrows and the like).
"""

# Windows virtual-key code -> Mac key code (kVK_* from Apple's Carbon Events.h)
WIN_TO_MAC = {
    # letters
    ord("A"): 0x00, ord("S"): 0x01, ord("D"): 0x02, ord("F"): 0x03, ord("H"): 0x04,
    ord("G"): 0x05, ord("Z"): 0x06, ord("X"): 0x07, ord("C"): 0x08, ord("V"): 0x09,
    ord("B"): 0x0B, ord("Q"): 0x0C, ord("W"): 0x0D, ord("E"): 0x0E, ord("R"): 0x0F,
    ord("Y"): 0x10, ord("T"): 0x11, ord("O"): 0x1F, ord("U"): 0x20, ord("I"): 0x22,
    ord("P"): 0x23, ord("L"): 0x25, ord("J"): 0x26, ord("K"): 0x28, ord("N"): 0x2D,
    ord("M"): 0x2E,
    # number row
    ord("1"): 0x12, ord("2"): 0x13, ord("3"): 0x14, ord("4"): 0x15, ord("5"): 0x17,
    ord("6"): 0x16, ord("7"): 0x1A, ord("8"): 0x1C, ord("9"): 0x19, ord("0"): 0x1D,
    # punctuation (US layout positions)
    0xBB: 0x18,  # = +
    0xBD: 0x1B,  # - _
    0xDB: 0x21,  # [ {
    0xDD: 0x1E,  # ] }
    0xDE: 0x27,  # ' "
    0xBA: 0x29,  # ; :
    0xDC: 0x2A,  # \ |
    0xBC: 0x2B,  # , <
    0xBF: 0x2C,  # / ?
    0xBE: 0x2F,  # . >
    0xC0: 0x32,  # ` ~
    # editing and movement
    0x0D: 0x24,  # Enter
    0x09: 0x30,  # Tab
    0x20: 0x31,  # Space
    0x08: 0x33,  # Backspace (Mac "delete")
    0x1B: 0x35,  # Esc
    0x2E: 0x75,  # Delete (Mac "forward delete")
    0x24: 0x73, 0x23: 0x77, 0x21: 0x74, 0x22: 0x79,  # Home, End, Page Up, Page Down
    0x25: 0x7B, 0x27: 0x7C, 0x28: 0x7D, 0x26: 0x7E,  # arrows: left, right, down, up
    0x2D: 0x72,  # Insert -> Help (same spot on full Mac keyboards)
    # modifiers
    0x10: 0x38, 0xA0: 0x38, 0xA1: 0x3C,  # Shift, left, right
    0x11: 0x3B, 0xA2: 0x3B, 0xA3: 0x3E,  # Ctrl, left, right
    0x12: 0x3A, 0xA4: 0x3A, 0xA5: 0x3D,  # Alt / Option, left, right
    0x5B: 0x37, 0x5C: 0x36,  # Windows key -> Command, left, right
    0x14: 0x39,  # Caps Lock
    # number pad
    0x60: 0x52, 0x61: 0x53, 0x62: 0x54, 0x63: 0x55, 0x64: 0x56,
    0x65: 0x57, 0x66: 0x58, 0x67: 0x59, 0x68: 0x5B, 0x69: 0x5C,
    0x6A: 0x43, 0x6B: 0x45, 0x6D: 0x4E, 0x6E: 0x41, 0x6F: 0x4B,
    # F-keys
    0x70: 0x7A, 0x71: 0x78, 0x72: 0x63, 0x73: 0x76, 0x74: 0x60, 0x75: 0x61,
    0x76: 0x62, 0x77: 0x64, 0x78: 0x65, 0x79: 0x6D, 0x7A: 0x67, 0x7B: 0x6F,
    0x7C: 0x69, 0x7D: 0x6B, 0x7E: 0x71, 0x7F: 0x6A, 0x80: 0x40, 0x81: 0x4F,
    0x82: 0x50, 0x83: 0x5A,  # F13 .. F20
}

# Mac key code -> Windows virtual-key code. Where several Windows codes share a Mac key (Shift and
# Left Shift), the left-hand one wins, like Windows itself reports it.
MAC_TO_WIN = {}
for _win, _mac in WIN_TO_MAC.items():
    if _win in (0x10, 0x11, 0x12):  # the "either side" modifier codes
        continue
    MAC_TO_WIN.setdefault(_mac, _win)
MAC_TO_WIN[0x4C] = 0x0D  # number pad Enter -> Enter
MAC_TO_WIN[0x47] = 0x90  # number pad Clear -> Num Lock (same spot)

# readable names for Windows key codes, for showing hotkeys on a Mac
_NAMES = {0xBB: "=", 0xBD: "-", 0xDB: "[", 0xDD: "]", 0xDE: "'", 0xBA: ";", 0xDC: "\\",
          0xBC: ",", 0xBF: "/", 0xBE: ".", 0xC0: "`", 0x0D: "Enter", 0x09: "Tab", 0x20: "Space",
          0x08: "Backspace", 0x1B: "Esc", 0x2E: "Delete", 0x24: "Home", 0x23: "End",
          0x21: "Page Up", 0x22: "Page Down", 0x25: "Left", 0x27: "Right", 0x26: "Up",
          0x28: "Down", 0x2D: "Insert", 0x14: "Caps Lock", 0x90: "Num Lock"}


def win_vk_name(vk):
    """A name for a Windows key code without asking Windows: 'A', '7', 'F5', ';' ... or None."""
    if 0x41 <= vk <= 0x5A or 0x30 <= vk <= 0x39:
        return chr(vk)
    if 0x70 <= vk <= 0x87:
        return f"F{vk - 0x6F}"
    return _NAMES.get(vk)
